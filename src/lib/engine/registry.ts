export function getModelArchitecture(modelOrId: ModelArchitecture | string): ModelArchitecture {
  if (typeof modelOrId === 'object' && modelOrId !== null) {
    return modelOrId
  }
  const found = MODEL_REGISTRY[modelOrId]
  if (!found) {
    throw new Error(`Model architecture '${modelOrId}' not found in registry.`)
  }
  return found
}

export function listSupportedModels(): ModelArchitecture[] {
  return Object.values(MODEL_REGISTRY)
}

/**
 * Creates an analytical fallback architecture when only parameter count is provided.
 * Assumes standard modern GQA proportions (e.g. 8 KV heads, 128 head dim).
 */
export function createFallbackArchitecture(paramCountB: number, name?: string): ModelArchitecture {
  // Approximate standard Transformer layer scaling
  const numLayers = Math.max(12, Math.min(96, Math.round(16 + paramCountB * 0.9)))
  const numAttentionHeads = Math.max(16, Math.min(64, Math.round(16 + paramCountB * 0.6)))
  const numKeyValueHeads = Math.max(4, Math.min(16, Math.round(numAttentionHeads / 4)))
  const headDimension = 128

  return {
    id: `custom-${paramCountB}b`,
    name: name || `Custom ${paramCountB}B Model (Analytical Fallback)`,
    family: 'custom',
    paramCountTotalB: paramCountB,
    numLayers,
    numAttentionHeads,
    numKeyValueHeads,
    headDimension,
    vocabSize: 128256,
    contextWindowMax: 32768,
    attentionType: 'GQA',
    description: 'Analytical approximation assuming standard modern GQA architecture.',
  }
}
